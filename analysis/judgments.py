"""Validated human decisions -> explicit, traceable edits to routing features.

Unobserved edges are not certified. Polygon presence never creates a centreline.
Final human decisions are inputs, never generated by this module.
"""
from dataclasses import replace
import hashlib
import json
from pathlib import Path

import pandas as pd
import numpy as np
import shapely
from shapely.geometry import LineString
from shapely.ops import substring

from analysis.routing import RouteFeature, geometry_hash

SCHEMA_VERSION = 1
PASSABILITY = {"통행가능", "통행불가", "판독불가"}
FINAL_LABELS = {
    "segment": {"분리형_자전거도로", "겸용_보도_표시있음", "노면표시_차로", "시설없음", "판독불가"},
    "candidate": {"물리적_단절", "실제로는_연결됨(기록만_끊김)", "공사중_또는_미개통", "판독불가"},
    "placeholder": {"실재", "미실재", "판독불가"},
}
FINAL_LABELS["island_gap"] = FINAL_LABELS["candidate"]


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def validate_matching_ids(left, right, *, name="sheets"):
    for frame in (left, right):
        if "pid" not in frame or frame["pid"].isna().any() or (frame["pid"].astype(str).str.strip() == "").any():
            raise ValueError(f"{name}: missing/blank pid")
        if frame["pid"].duplicated().any():
            raise ValueError(f"{name}: duplicate pid")
    if set(left["pid"]) != set(right["pid"]):
        raise ValueError(f"{name}: missing or unexpected pid (complete frozen manifest required)")


def compile_decisions(samples, final, features):
    """Compile only decisions supplied by human reviewers; match exact target extents."""
    validate_matching_ids(samples, final, name="final decisions")
    required = {"pid", "final_label", "passability", "reason", "reviewed_by"}
    if not required <= set(final):
        raise ValueError(f"missing final columns: {sorted(required-set(final))}")
    merged = samples.merge(final, on="pid", validate="one_to_one", suffixes=("", "_final"))
    operations = []
    for _, row in merged.iterrows():
        pid = str(row["pid"])
        if row["passability"] not in PASSABILITY or not str(row["reason"]).strip() or not str(row["reviewed_by"]).strip():
            raise ValueError(f"{pid}: human passability, reason and reviewer are required")
        label = str(row["final_label"]).strip()
        if label not in FINAL_LABELS.get(row["sample_type"], set()):
            raise ValueError(f"{pid}: invalid final_label for sample_type")
        if label in {"물리적_단절", "공사중_또는_미개통"} and row["passability"] == "통행가능":
            raise ValueError(f"{pid}: contradictory facility/path presence and passability")
        base = {"pid": pid, "label": label, "passability": row["passability"],
                "reason": row["reason"], "reviewed_by": row["reviewed_by"]}
        geom_text = row.get("target_wkt", "")
        if not isinstance(geom_text, str) or not geom_text.strip():
            raise ValueError(f"{pid}: target geometry is required; a midpoint is insufficient")
        geom = shapely.from_wkt(geom_text)
        if not geom.is_valid or geom.is_empty:
            raise ValueError(f"{pid}: invalid target geometry")
        if label == "판독불가" or row["passability"] == "판독불가":
            operations.append({**base, "action": "unresolved"})
            continue
        sample_type = row["sample_type"]
        if sample_type in {"candidate", "island_gap"}:
            if label == "실제로는_연결됨(기록만_끊김)" and row["passability"] == "통행가능":
                if geom.geom_type != "LineString":
                    raise ValueError(f"{pid}: a confirmed path LineString is required")
                # A straight chord is not always the observed connection.
                path_text = row.get("connection_wkt", "")
                if not isinstance(path_text, str) or not path_text.strip():
                    raise ValueError(f"{pid}: provide the observed connection_wkt, not just its gap midpoint")
                path = shapely.from_wkt(path_text)
                if path.geom_type != "LineString" or not path.is_simple or path.length <= 0:
                    raise ValueError(f"{pid}: invalid observed connection")
                direct = max(path.boundary.hausdorff_distance(geom.boundary), 0)
                if direct > 1.0:
                    raise ValueError(f"{pid}: observed path endpoints differ from target gap by >1m")
                operations.append({**base, "action": "add", "geometry_wkt": path.wkt,
                                   "geometry_hash": geometry_hash(path), "level": str(row.get("level", "0")),
                                   "direction": int(row.get("direction", 0))})
            else:
                operations.append({**base, "action": "no_connection", "target_wkt": geom.wkt})
            continue
        if geom.geom_type != "LineString":
            operations.append({**base, "action": "observation_only", "note": "polygon does not define a route"})
            continue
        if label in {"시설없음", "미실재"} and row["passability"] == "통행가능":
            operations.append({**base, "action": "observation_only",
                               "note": "facility absent but general road may be passable; route classification unresolved"})
            continue
        should_remove = label in {"시설없음", "미실재"} or row["passability"] == "통행불가"
        if not should_remove:
            operations.append({**base, "action": "keep"})
            continue
        candidates = []
        source = str(row.get("source_origin", ""))
        for feature in features:
            if source and feature.source != source:
                continue
            start, end = sorted(feature.geometry.project(shapely.Point(p)) for p in (geom.coords[0], geom.coords[-1]))
            if end - start <= 1e-8:
                continue
            part = substring(feature.geometry, start, end)
            if part.hausdorff_distance(geom) <= 1e-5 and abs(part.length - geom.length) <= 1e-4:
                candidates.append((feature, start, end))
        if not candidates:
            raise ValueError(f"{pid}: cannot map target to source line; specify the exact observed segment")
        # Multiple identical source representations are explicitly enumerated;
        # no 10m buffer deletion or entire-feature drop is permitted.
        for feature, start, end in candidates:
            operations.append({**base, "action": "remove", "fid": feature.fid,
                               "source_geometry_hash": geometry_hash(feature.geometry),
                               "start_m": start, "end_m": end})
    return {"schema_version": SCHEMA_VERSION, "crs": "EPSG:5186",
            "sample_count": len(samples), "coverage": "partial_sample_only", "operations": operations}


def apply_corrections(features, manifest):
    if isinstance(manifest, (str, Path)):
        manifest = json.loads(Path(manifest).read_text())
    if manifest.get("schema_version") != SCHEMA_VERSION or manifest.get("crs") != "EPSG:5186":
        raise ValueError("unsupported correction schema/CRS")
    removals, additions = {}, []
    allowed = {"remove", "add", "keep", "unresolved", "no_connection", "observation_only"}
    for op in manifest.get("operations", []):
        if op.get("action") not in allowed:
            raise ValueError("unknown correction action")
        if op["action"] in {"add", "remove"} and (not op.get("reviewed_by") or not op.get("reason")):
            raise ValueError("network edits require human evidence and attribution")
        if op["action"] == "remove":
            removals.setdefault(op["fid"], []).append(op)
        elif op["action"] == "add":
            geom = shapely.from_wkt(op["geometry_wkt"])
            if geometry_hash(geom) != op["geometry_hash"]:
                raise ValueError("added geometry hash mismatch")
            additions.append(RouteFeature(f"judged:{op['pid']}", geom,
                                           direction=int(op.get("direction", 0)),
                                           level=str(op.get("level", "0")), source="judged"))
    result = []
    for feature in features:
        ops = removals.get(feature.fid, [])
        if not ops:
            result.append(feature)
            continue
        intervals = []
        for op in ops:
            if op["source_geometry_hash"] != geometry_hash(feature.geometry):
                raise ValueError(f"stale source geometry: {feature.fid}")
            start, end = float(op["start_m"]), float(op["end_m"])
            if not (0 <= start < end <= feature.geometry.length + 1e-6):
                raise ValueError("invalid removal interval")
            intervals.append((start, min(end, feature.geometry.length)))
        cursor = 0.0
        for start, end in sorted(intervals) + [(feature.geometry.length, feature.geometry.length)]:
            if start > cursor + 1e-8:
                part = substring(feature.geometry, cursor, start)
                refs = ()
                if len(feature.node_refs) == len(feature.geometry.coords):
                    original_xy = np.asarray(feature.geometry.coords)[:, :2]
                    old_offsets = np.r_[0., np.cumsum(np.linalg.norm(np.diff(original_xy, axis=0), axis=1))]
                    part_xy = np.asarray(part.coords)[:, :2]
                    offsets = cursor + np.r_[0., np.cumsum(np.linalg.norm(np.diff(part_xy, axis=0), axis=1))]
                    refs_list = []
                    for offset in offsets:
                        nearest = int(np.argmin(np.abs(old_offsets-offset)))
                        refs_list.append(feature.node_refs[nearest] if abs(old_offsets[nearest]-offset) < 1e-6 else None)
                    refs = tuple(refs_list)
                result.append(replace(feature, fid=f"{feature.fid}:retained:{cursor:.8f}:{start:.8f}",
                                      geometry=part, node_refs=refs))
            cursor = max(cursor, end)
    result.extend(additions)
    return result, {"input_features": len(features), "output_features": len(result),
                    "operations": len(manifest.get("operations", [])), "coverage": "partial_sample_only"}


def compile_files(root, final_path, output_path):
    from analysis.routing import load_features
    root = Path(root)
    manifest_path = root / "outputs/private/judging_manifest.csv"
    from analysis.judging_packet import read_manifest
    samples = read_manifest(manifest_path.parent)
    final = pd.read_csv(final_path, keep_default_na=False)
    # The scoring stage certifies completion, not correctness. Require its exact
    # frozen manifest so decisions cannot silently target a newly sampled set.
    payload = compile_decisions(samples, final, load_features(root, "lowstress"))
    payload.update(sample_sha256=file_hash(manifest_path), final_sha256=file_hash(final_path))
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    return payload
